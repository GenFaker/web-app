"""Explicit lifecycle and recoverable failure checks against an isolated preview."""
from pathlib import Path
from uuid import uuid4
from playwright.sync_api import sync_playwright, expect

BASE = 'http://127.0.0.1:8767'
with sync_playwright() as engine:
    browser = engine.chromium.launch(channel='chrome', headless=True)
    page = browser.new_page(viewport={'width': 1440, 'height': 1050})
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    # Exercise the genuinely empty workspace UI without changing stored data.
    page.route('**/api/workspace', lambda route: route.fulfill(json={'folders': [], 'assessments': []}))
    page.goto(BASE)
    expect(page.locator('#network-canvas')).to_be_visible()
    assert page.locator('#dashboard-view .create-trigger').count() == 0
    page.locator('nav [data-view=library]').click()
    page.locator('#library-view .create-trigger').first.click()
    expect(page.locator('#app-error')).to_contain_text('Create a folder')
    expect(page.locator('#create-dialog')).not_to_be_visible()
    page.unroute('**/api/workspace')
    page.reload()
    page.locator('nav [data-view=library]').click()
    page.locator('#new-folder').click()
    page.locator('#folder-submit').click()
    expect(page.locator('#folder-dialog .dialog-error')).to_contain_text('Enter a folder name')
    page.locator('#folder-name').fill('Lifecycle ' + uuid4().hex[:6])
    page.route('**/api/folders', lambda route: route.fulfill(status=500, json={'detail': 'Folder storage unavailable'}))
    page.locator('#folder-submit').click()
    expect(page.locator('#folder-dialog .dialog-error')).to_contain_text('Folder storage unavailable')
    page.unroute('**/api/folders')
    page.locator('#folder-submit').click()
    expect(page.locator('#folder-dialog')).not_to_be_visible()
    page.locator('#library-all-folders').click()
    page.locator('#library-view .create-trigger').first.click()
    page.locator('#create-title').fill('Read-only lifecycle')
    page.locator('#create-submit').click()
    expect(page.locator('#create-dialog .dialog-error')).to_contain_text('Choose the folder')
    folder_id = page.locator('#create-folder option').nth(1).get_attribute('value')
    page.locator('#create-folder').select_option(folder_id)
    page.locator('#create-title').fill('  ')
    page.locator('#create-submit').click()
    expect(page.locator('#create-dialog .dialog-error')).to_contain_text('Enter an assessment name')
    page.locator('#create-title').fill('Read-only lifecycle')
    page.locator('#create-submit').click()
    expect(page.locator('#assessment-editor')).to_be_visible()
    page.locator('#checklist input[name=storage_files][value=yes]').check()
    page.locator('#finish-editing').click()
    expect(page.locator('#review-view')).to_be_visible()
    assert page.locator('#review-view input, #review-view textarea').count() == 0
    expect(page.locator('#review-view')).to_contain_text('Draft · not yet assessed')
    page.locator('#begin-edit').click()
    page.locator('#project-title').fill('')
    page.locator('#save-assessment').click()
    expect(page.locator('#app-error')).to_contain_text('Enter an assessment name')
    expect(page.locator('#checklist input[name=storage_files][value=yes]')).to_be_checked()
    page.locator('#project-title').fill('Read-only lifecycle')
    page.locator('#finish-editing').click()
    page.locator('nav [data-view=planning]').click()
    token = page.locator('meta[name=advisory-token]').get_attribute('content')
    headers = {'X-Advisory-Token': token}
    workspace = page.request.get(BASE + '/api/workspace', headers=headers).json()
    record = next(a for a in workspace['assessments'] if a['title'] == 'Read-only lifecycle')
    page.locator('#notes-assessment').select_option(record['id'])
    expect(page.locator('#notes-panel')).to_be_visible()
    page.locator('#planning-notes').fill('Retain this mitigation note on failure.')
    page.route('**/api/assessments/' + record['id'], lambda route: route.fulfill(status=500, json={'detail':'Save failed'}))
    page.locator('#save-notes').click()
    expect(page.locator('#notes-status')).to_contain_text('Your notes remain here')
    page.locator('nav [data-view=library]').click()
    expect(page.locator('#planning-view')).to_be_visible()
    expect(page.locator('#planning-notes')).to_have_value('Retain this mitigation note on failure.')
    page.unroute('**/api/assessments/' + record['id'])
    page.locator('#save-notes').click()
    expect(page.locator('#notes-status')).to_contain_text('saved')
    page.locator('nav [data-view=library]').click()
    page.locator(f'[data-open-assessment="{record["id"]}"]').click()
    expect(page.locator('#review-view')).to_be_visible()
    for width in (1440, 390):
        page.set_viewport_size({'width': width, 'height': 1050})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        Path('work/browser-checks').mkdir(parents=True, exist_ok=True)
        page.screenshot(path=f'work/browser-checks/record-{width}.png', full_page=True)
    page.once('dialog', lambda dialog: dialog.dismiss())
    page.locator('#delete-assessment').click()
    expect(page.locator('#review-view')).to_be_visible()
    page.route('**/api/assessments/' + record['id'] + '?revision=*', lambda route: route.fulfill(status=500, json={'detail':'Delete failed'}))
    page.once('dialog', lambda dialog: dialog.accept())
    page.locator('#delete-assessment').click()
    expect(page.locator('#app-error')).to_contain_text('Delete failed')
    expect(page.locator('#delete-assessment')).to_be_enabled()
    page.unroute('**/api/assessments/' + record['id'] + '?revision=*')
    page.once('dialog', lambda dialog: dialog.accept())
    page.locator('#delete-assessment').click()
    expect(page.locator('#library-view')).to_be_visible()
    assert page.request.get(BASE + '/api/assessments/' + record['id'], headers=headers).status == 404
    assert not errors, errors
    browser.close()
    print('Lifecycle, folder gates, modal errors, read-only review, explicit editing, retained failed saves, delete cancellation/failure/success, and responsive record checks passed.')
